// Reads the board colours straight from lib/core/theme/board_theme.dart,
// so the web never re-types a palette.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DART_BOARD_THEME = fileURLToPath(new URL('../../lib/core/theme/board_theme.dart', import.meta.url));

/** ARGB ints by constant name, in file order. */
export function parseBoardTheme(src: string = readFileSync(DART_BOARD_THEME, 'utf8')): Record<string, number> {
  const out: Record<string, number> = {};
  for (const m of src.matchAll(/static const (\w+) = Color\(0x([0-9A-Fa-f]{8})\);/g)) out[m[1]] = parseInt(m[2], 16);
  if (Object.keys(out).length === 0) throw new Error('No colours found in board_theme.dart');
  return out;
}

/** ARGB int → CSS colour: #RRGGBB when opaque, rgba() otherwise. */
export function argbToCss(argb: number): string {
  const a = (argb >>> 24) & 0xff;
  const rgb = argb & 0xffffff;
  if (a === 0xff) return `#${rgb.toString(16).padStart(6, '0').toUpperCase()}`;
  const r = (rgb >> 16) & 0xff;
  const g = (rgb >> 8) & 0xff;
  const b = rgb & 0xff;
  return `rgba(${r},${g},${b},${+(a / 255).toFixed(4)})`;
}

export function renderBoardTheme(colors: Record<string, number>): string {
  const lines = Object.entries(colors).map(([k, v]) => `  ${k}: '${argbToCss(v)}',`);
  return [
    '// GENERATED by `npm run gen` from lib/core/theme/board_theme.dart. Do not edit.',
    'export const BOARD_THEME = {',
    ...lines,
    '} as const;',
    '',
  ].join('\n');
}
